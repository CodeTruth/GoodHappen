/**
 * 根据用户描述匹配相关法律条文
 */
export function matchLegalArticles(userText: string): LegalArticle[] {
  const text = userText.toLowerCase();
  return LEGAL_KNOWLEDGE.filter(article =>
    article.keywords.some(kw => text.includes(kw))
  );
}

/**
 * 格式化法律知识为prompt文本
 */
export function formatLegalForPrompt(articles: LegalArticle[]): string {
  if (articles.length === 0) return '';
  return '\n【相关法律知识 — 请在回复中自然引用，给用户法律底气】\n' +
    articles.map(a =>
      `${a.law}${a.article}（${a.shortName}）：\n  原文：${a.text}\n  解读：${a.plainExplanation}\n  对善行者的保护：${a.protectionForHelper}`
    ).join('\n\n');
}

