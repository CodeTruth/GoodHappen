// 获取所有省份名称
export const getProvinceNames = (): string[] => {
  return regions.map(r => r.name);
};

// 根据省份索引获取城市列表
export const getCitiesByProvinceIndex = (provinceIndex: number): string[] => {
  if (provinceIndex < 0 || provinceIndex >= regions.length) return [];
  return regions[provinceIndex].cities;
};

// 根据省份名称获取城市列表
export const getCitiesByProvinceName = (provinceName: string): string[] => {
  const region = regions.find(r => r.name === provinceName);
  return region ? region.cities : [];
};
